-- ESTRUTURA DO ACERVO AUDIOVISUAL — PostgreSQL
-- PRIMARY KEY: identifica cada linha. IDENTITY gera o ID automaticamente.
-- FOREIGN KEY / REFERENCES: cria uma referência entre tabelas.
-- ON DELETE RESTRICT: bloqueia a exclusão de um cadastro com dependentes.
-- NOT NULL: exige um valor. UNIQUE: impede duplicação da chave indicada.
-- CHECK: valida uma regra. DEFAULT: fornece um valor quando ele é omitido.
-- JSONB: conserva documentos originais e informações estruturadas em JSON.

-- 1. Criar o esquema e definir onde as tabelas serão procuradas
-- Um esquema organiza as tabelas dentro do banco.
CREATE SCHEMA IF NOT EXISTS audiovisual;
SET search_path TO audiovisual, public;


-- 2. Fontes e importações
-- Guarda as instituições que forneceram os registros, como ANCINE e Cinemateca.
CREATE TABLE IF NOT EXISTS fonte_dados (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome varchar(160) NOT NULL UNIQUE, url text, descricao text
);

-- Identifica cada conjunto de dados importado e a fonte à qual ele pertence.
-- O hash permite conferir o arquivo de origem. A combinação UNIQUE evita repetir o mesmo lote.
CREATE TABLE IF NOT EXISTS lote_importacao (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 fonte_id bigint NOT NULL REFERENCES fonte_dados(id) ON DELETE RESTRICT,
 nome varchar(240) NOT NULL, sha256 varchar(64) NOT NULL,
 data_importacao timestamptz NOT NULL DEFAULT current_timestamp,
 observacao text,
 CHECK (sha256 ~ '^[a-f0-9]{64}$'), UNIQUE(fonte_id,nome,sha256)
);

-- Vocabulário dos tipos de obra declarados nas fontes.
CREATE TABLE IF NOT EXISTS tipo_obra (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome varchar(200) NOT NULL UNIQUE, descricao text
);

-- 3. Obras e descrições
-- Representa a obra cadastrada, com título, nível e situação.
-- O ID é a chave primária. A chave técnica de origem serve para rastrear a importação.
CREATE TABLE IF NOT EXISTS obra (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 chave_tcc text UNIQUE,
 titulo_referencia text NOT NULL CHECK (length(btrim(titulo_referencia))>0),
 nivel varchar(40) NOT NULL DEFAULT 'obra',
 status varchar(80) NOT NULL DEFAULT 'cadastrada',
 observacao text,
 CHECK (nivel IN ('obra','serie','episodio','temporada','nao_especificado'))
);

-- Guarda o que uma fonte declarou sobre uma obra.
-- Cada registro aponta para uma obra e um lote. Ano e duração são validados.
-- Os JSONs conservam o original, o perfil e a proveniência de cada descrição.
CREATE TABLE IF NOT EXISTS registro_fonte (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 obra_id bigint NOT NULL REFERENCES obra(id) ON DELETE RESTRICT,
 lote_id bigint NOT NULL REFERENCES lote_importacao(id) ON DELETE RESTRICT,
 tipo_obra_id bigint REFERENCES tipo_obra(id) ON DELETE RESTRICT,
 chave_origem text NOT NULL UNIQUE, identificador_fonte text,
 ano integer CHECK (ano BETWEEN 1800 AND 2100),
 duracao_minutos numeric(12,3) CHECK (duracao_minutos>0),
 original_json jsonb NOT NULL DEFAULT '{}',
 perfil_json jsonb NOT NULL DEFAULT '{}',
 proveniencia_json jsonb NOT NULL DEFAULT '{}',
 observacao text
);

-- Armazena os títulos declarados, alternativos e usados na comparação.
-- Um mesmo registro pode ter vários títulos, mas não repete a mesma combinação.
CREATE TABLE IF NOT EXISTS titulo (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 registro_id bigint NOT NULL REFERENCES registro_fonte(id) ON DELETE RESTRICT,
 valor text NOT NULL CHECK (length(btrim(valor))>0),
 tipo varchar(40) NOT NULL DEFAULT 'declarado',
 CHECK(tipo IN ('declarado','alternativo','chave_normalizada')),
 UNIQUE(registro_id,valor,tipo)
);

-- 4. Certificados administrativos
-- Registra número, esquema, papel e data do certificado ligado a um registro.
-- O papel distingue, por exemplo, um CPB da obra de uma referência à série.
CREATE TABLE IF NOT EXISTS certificado (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 registro_id bigint NOT NULL REFERENCES registro_fonte(id) ON DELETE RESTRICT,
 numero varchar(160) NOT NULL, esquema varchar(80) NOT NULL DEFAULT 'CPB',
 papel varchar(60) NOT NULL DEFAULT 'nao_especificado',
 data_emissao date, situacao text,
 UNIQUE(registro_id,numero,esquema,papel)
);

-- 5. Pessoas, empresas e participações
-- Guarda os nomes de pessoas conforme a fonte. Nomes iguais em fontes distintas não provam identidade.
CREATE TABLE IF NOT EXISTS pessoa (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 fonte_id bigint NOT NULL REFERENCES fonte_dados(id) ON DELETE RESTRICT,
 nome text NOT NULL CHECK(length(btrim(nome))>0),
 observacao text, UNIQUE(fonte_id,nome)
);

-- Guarda organizações e requerentes conforme a fonte.
-- O município pertence ao requerente e não é tratado como local de produção da obra.
CREATE TABLE IF NOT EXISTS empresa (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 fonte_id bigint NOT NULL REFERENCES fonte_dados(id) ON DELETE RESTRICT,
 nome text NOT NULL CHECK(length(btrim(nome))>0),
 cnpj varchar(32), uf varchar(2), municipio text, observacao text,
 UNIQUE(fonte_id,nome)
);

-- Lista funções como direção, roteiro e elenco.
CREATE TABLE IF NOT EXISTS funcao_credito (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome varchar(160) NOT NULL UNIQUE, descricao text
);

-- Liga um registro a uma pessoa e à função exercida.
-- Resolve participações de muitas pessoas em muitos registros, preservando função e evidência.
CREATE TABLE IF NOT EXISTS credito_pessoa (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 registro_id bigint NOT NULL REFERENCES registro_fonte(id) ON DELETE RESTRICT,
 pessoa_id bigint NOT NULL REFERENCES pessoa(id) ON DELETE RESTRICT,
 funcao_id bigint NOT NULL REFERENCES funcao_credito(id) ON DELETE RESTRICT,
 personagem text, evidencia text,
 UNIQUE(registro_id,pessoa_id,funcao_id)
);

-- Liga uma empresa a um registro e informa seu papel, como requerente ou produtora.
CREATE TABLE IF NOT EXISTS participacao_empresa (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 registro_id bigint NOT NULL REFERENCES registro_fonte(id) ON DELETE RESTRICT,
 empresa_id bigint NOT NULL REFERENCES empresa(id) ON DELETE RESTRICT,
 papel varchar(80) NOT NULL,
 evidencia text, UNIQUE(registro_id,empresa_id,papel)
);

-- 6. Países, gêneros e características
-- Vocabulário de países informados nas fontes.
CREATE TABLE IF NOT EXISTS pais (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome varchar(200) NOT NULL UNIQUE
);

-- Relaciona os países aos registros que declaram essa informação.
-- A combinação de registro e país não pode ser repetida.
CREATE TABLE IF NOT EXISTS obra_pais (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 registro_id bigint NOT NULL REFERENCES registro_fonte(id) ON DELETE RESTRICT,
 pais_id bigint NOT NULL REFERENCES pais(id) ON DELETE RESTRICT,
 evidencia text, UNIQUE(registro_id,pais_id)
);

-- Vocabulário de gêneros declarados nas fontes.
CREATE TABLE IF NOT EXISTS genero (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome varchar(200) NOT NULL UNIQUE
);

-- Relaciona registros e gêneros em uma associação de muitos para muitos.
CREATE TABLE IF NOT EXISTS obra_genero (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 registro_id bigint NOT NULL REFERENCES registro_fonte(id) ON DELETE RESTRICT,
 genero_id bigint NOT NULL REFERENCES genero(id) ON DELETE RESTRICT,
 UNIQUE(registro_id,genero_id)
);

-- Guarda características como material, duração declarada e unidade de medida.
CREATE TABLE IF NOT EXISTS caracteristica_tecnica (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 registro_id bigint NOT NULL REFERENCES registro_fonte(id) ON DELETE RESTRICT,
 nome varchar(120) NOT NULL, valor text NOT NULL, unidade varchar(80),
 UNIQUE(registro_id,nome,valor)
);

-- 7. Relações e revisão de integração
-- Relaciona obras diferentes, como um episódio e sua série.
-- O CHECK impede que uma obra seja origem e destino da mesma relação.
CREATE TABLE IF NOT EXISTS relacao_obra (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 origem_id bigint NOT NULL REFERENCES obra(id) ON DELETE RESTRICT,
 destino_id bigint NOT NULL REFERENCES obra(id) ON DELETE RESTRICT,
 tipo varchar(100) NOT NULL, status varchar(120) NOT NULL,
 evidencia_json jsonb NOT NULL DEFAULT '{}',
 CHECK(origem_id<>destino_id), UNIQUE(origem_id,destino_id,tipo)
);

-- Registra o parecer sobre dois registros, com justificativa, responsável e data.
-- Os registros precisam ser diferentes. O parecer não executa fusão automática.
CREATE TABLE IF NOT EXISTS decisao_integracao (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 registro_a_id bigint NOT NULL REFERENCES registro_fonte(id) ON DELETE RESTRICT,
 registro_b_id bigint NOT NULL REFERENCES registro_fonte(id) ON DELETE RESTRICT,
 parecer varchar(40) NOT NULL,
 justificativa text NOT NULL CHECK(length(btrim(justificativa))>0),
 responsavel varchar(200) NOT NULL,
 data_decisao timestamptz NOT NULL DEFAULT current_timestamp,
 CHECK(registro_a_id<>registro_b_id),
 CHECK(parecer IN ('mesma_obra','obras_distintas','incerto','episodio_da_serie'))
);
-- 8. Índices para localizar referências e filtros com mais eficiência
-- Ajudam nas buscas e junções. Não substituem as restrições de integridade.
CREATE INDEX IF NOT EXISTS registro_obra_idx ON registro_fonte(obra_id);
CREATE INDEX IF NOT EXISTS registro_lote_idx ON registro_fonte(lote_id);
CREATE INDEX IF NOT EXISTS registro_tipo_idx ON registro_fonte(tipo_obra_id);
CREATE INDEX IF NOT EXISTS registro_ano_idx ON registro_fonte(ano);
CREATE INDEX IF NOT EXISTS certificado_registro_idx ON certificado(registro_id);
CREATE INDEX IF NOT EXISTS credito_registro_idx ON credito_pessoa(registro_id);
CREATE INDEX IF NOT EXISTS participacao_registro_idx ON participacao_empresa(registro_id);
CREATE INDEX IF NOT EXISTS titulo_busca_idx ON titulo(registro_id);

